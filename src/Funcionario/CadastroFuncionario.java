    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed

    beans.Funcionario func = new beans.Funcionario();
        func.setNome(txtNome.getText().trim());
        func.setCargo(txtCargo.getText().trim());
        func.setEmail(txtEmail.getText().trim());

        Object eqSelecionada = cmbEquipe.getSelectedItem();
        if (eqSelecionada instanceof beans.Equipe) {
            func.setIdEquipe(((beans.Equipe) eqSelecionada).getId());
        } else {
            func.setIdEquipe(null);
        }

        new DAO.FuncionarioDAO().inserir(func);
        javax.swing.JOptionPane.showMessageDialog(this, "Funcionário salvo!");

        txtNome.setText("");
        txtCargo.setText("");
        txtEmail.setText("");
        if (cmbEquipe.getItemCount() > 0) {
            cmbEquipe.setSelectedIndex(0);
        }   
        

    }//GEN-LAST:event_btnSalvarActionPerformed
    
