    private void btnConsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarActionPerformed
       if (txtId.getText().trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Digite um ID válido para consultar!", "Atenção", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        try {
            int idPesquisa = Integer.parseInt(txtId.getText().trim());
            
            DAO.FuncionarioDAO dao = new DAO.FuncionarioDAO();
            beans.Funcionario f = dao.buscarPorId(idPesquisa);
            
            if (f != null) {
                txtDisable.setText(String.valueOf(f.getId()));
                txtNome.setText(f.getNome());
                txtCargo.setText(f.getCargo());
                txtEmail.setText(f.getEmail());
                
                javax.swing.JOptionPane.showMessageDialog(this, "Funcionário encontrado com sucesso!", "Sucesso", javax.swing.JOptionPane.INFORMATION_MESSAGE);
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Nenhum funcionário encontrado com o ID " + idPesquisa + ".", "Não Encontrado", javax.swing.JOptionPane.ERROR_MESSAGE);
                limparCampos();
            }
            
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "O ID precisa ser um número inteiro válido!", "Erro de Formato", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnConsultarActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        if (txtDisable.getText().trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Consulte um funcionário primeiro antes de tentar editá-lo!", "Atenção", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        beans.Funcionario f = new beans.Funcionario();
        f.setId(Integer.parseInt(txtDisable.getText().trim()));
        f.setNome(txtNome.getText().trim());
        f.setCargo(txtCargo.getText().trim());
        f.setEmail(txtEmail.getText().trim());
        
        DAO.FuncionarioDAO dao = new DAO.FuncionarioDAO();
        dao.editar(f);
        
        javax.swing.JOptionPane.showMessageDialog(this, "Funcionário atualizado com sucesso!", "Sucesso", javax.swing.JOptionPane.INFORMATION_MESSAGE);
        limparCampos();
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        if (txtDisable.getText().trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Consulte um funcionário primeiro antes de tentar excluí-lo!", "Atenção", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        int confirma = javax.swing.JOptionPane.showConfirmDialog(this, "Tem certeza que deseja excluir permanentemente este funcionário?", "Confirmação", javax.swing.JOptionPane.YES_NO_OPTION);
        
        if (confirma == javax.swing.JOptionPane.YES_OPTION) {
            int idExclusao = Integer.parseInt(txtDisable.getText().trim());
            
          DAO.FuncionarioDAO dao = new DAO.FuncionarioDAO();
            dao.excluir(idExclusao);
            
            javax.swing.JOptionPane.showMessageDialog(this, "Funcionário excluído com sucesso!", "Excluído", javax.swing.JOptionPane.INFORMATION_MESSAGE);
            limparCampos();
        }
    }                                          

    private void limparCampos() {
        txtId.setText("");
        txtDisable.setText("");
        txtNome.setText("");
        txtCargo.setText("");
        txtEmail.setText("");
    }//GEN-LAST:event_btnExcluirActionPerformed

