    private void btnConsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarActionPerformed
       if (txtId.getText().trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, 
                "Digite um ID no campo superior para consultar!", 
                "Atenção", 
                javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        try {
            int idPesquisa = Integer.parseInt(txtId.getText().trim());
            
            // Chama o DAO para buscar no banco
            DAO.ProjetoDAO dao = new DAO.ProjetoDAO();
            beans.Projeto p = dao.getPorId(idPesquisa);
            
            if (p != null) {
                // Achou! Joga os dados nos campos inferiores (inclusive o ID travado no txtDisable)
                txtDisable.setText(String.valueOf(p.getId()));
                txtNome.setText(p.getNomeProjeto());
                txtDescricao.setText(p.getDescricao());
                txtCliente.setText(p.getCliente());
                
                javax.swing.JOptionPane.showMessageDialog(this, 
                    "Projeto encontrado com sucesso!", 
                    "Sucesso", 
                    javax.swing.JOptionPane.INFORMATION_MESSAGE);
            } else {
                // Não achou no banco
                javax.swing.JOptionPane.showMessageDialog(this, 
                    "Nenhum projeto encontrado com o ID " + idPesquisa + ".", 
                    "Não Encontrado", 
                    javax.swing.JOptionPane.ERROR_MESSAGE);
                limparCampos();
            }
            
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, 
                "O ID precisa ser um número inteiro válido!", 
                "Erro de Formato", 
                javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnConsultarActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
      if (txtDisable.getText().trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, 
                "Consulte um projeto primeiro antes de tentar editá-lo!", 
                "Atenção", 
                javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        // Pega os dados alterados da tela
        beans.Projeto p = new beans.Projeto();
        p.setId(Integer.parseInt(txtDisable.getText().trim())); // Pega o ID seguro do txtDisable
        p.setNomeProjeto(txtNome.getText().trim());
        p.setDescricao(txtDescricao.getText().trim());
        p.setCliente(txtCliente.getText().trim());
        
        // Dispara o UPDATE no DAO
        DAO.ProjetoDAO dao = new DAO.ProjetoDAO();
        dao.editar(p);
        
        javax.swing.JOptionPane.showMessageDialog(this, 
            "Projeto atualizado com sucesso!", 
            "Sucesso", 
            javax.swing.JOptionPane.INFORMATION_MESSAGE);
            
        limparCampos();
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
                                             
        // Valida se há um projeto carregado
        if (txtDisable.getText().trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, 
                "Consulte um projeto primeiro antes de tentar excluí-lo!", 
                "Atenção", 
                javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        // Caixa de confirmação obrigatória para evitar exclusão acidental
        int confirma = javax.swing.JOptionPane.showConfirmDialog(this, 
            "Tem certeza que deseja excluir permanentemente este projeto?", 
            "Confirmação de Exclusão", 
            javax.swing.JOptionPane.YES_NO_OPTION);
            
        if (confirma == javax.swing.JOptionPane.YES_OPTION) {
            int idExclusao = Integer.parseInt(txtDisable.getText().trim());
            
            DAO.ProjetoDAO dao = new DAO.ProjetoDAO();
            dao.excluir(idExclusao);
            
            javax.swing.JOptionPane.showMessageDialog(this, 
                "Projeto excluído com sucesso!", 
                "Excluído", 
                javax.swing.JOptionPane.INFORMATION_MESSAGE);
                
            limparCampos();
        }
    }                                          

    // Método auxiliar para limpar todos os campos da tela
    private void limparCampos() {
        txtId.setText("");
        txtDisable.setText("");
        txtNome.setText("");
        txtDescricao.setText("");
        txtCliente.setText("");
    
    }//GEN-LAST:event_btnExcluirActionPerformed

