    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
 beans.Projeto p = new beans.Projeto();
        p.setNomeProjeto(txtNomeProjeto.getText().trim());
        p.setDescricao(txtDescricao.getText().trim());
        p.setCliente(txtCliente.getText().trim());
        p.setDataInicio(java.time.LocalDate.now());

        Object selecionada = cmbEquipe.getSelectedItem();
        if (selecionada instanceof beans.Equipe) {
            p.setIdEquipe(((beans.Equipe) selecionada).getId());
        } else {
            p.setIdEquipe(null);
        }

        new DAO.ProjetoDAO().inserir(p);
        javax.swing.JOptionPane.showMessageDialog(this, "Projeto salvo com sucesso!");
        carregarComboEquipes();
    }//GEN-LAST:event_btnSalvarActionPerformed

