private void carregarComboEquipes() {
    cmbEquipe.removeAllItems();
    cmbEquipe.addItem(null); // opcional: permite projeto sem equipe

    DAO.EquipeDAO equipeDAO = new DAO.EquipeDAO();
    for (beans.Equipe eq : equipeDAO.getEquipes()) {
        cmbEquipe.addItem(eq);
    }
}

