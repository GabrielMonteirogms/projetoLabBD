    private void btnFiltrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFiltrarActionPerformed
        String moduloSelecionado = cmbFiltroModulo.getSelectedItem().toString();
        BugDAO bDAO = new BugDAO();
        
        if (moduloSelecionado.equals("Todos")) {
            // Se quer todos, chama o método genérico e joga pra tabela
            List<Bug> todos = bDAO.getBugs();
            preencherTabela(todos);
        } else {
            // Se escolheu um específico, chama a query com WHERE e joga pra tabela
            List<Bug> filtrados = bDAO.getBugsPorModulo(moduloSelecionado);
            preencherTabela(filtrados);
        }
    }//GEN-LAST:event_btnFiltrarActionPerformed

