    public void preencherTabela(List<Bug> listaBugs) {
 DefaultTableModel tabelaBugs = (DefaultTableModel) tbl_Bugs.getModel();
        tabelaBugs.setNumRows(0); // Limpa a tabela antes de desenhar
        
        if (listaBugs != null) {
            for(Bug b : listaBugs){
                Object[] obj = new Object[] {
                    b.getId(),
                    b.getNome(),
                    b.getDescricao(),
                    b.getStatus(),
                    b.getModulo(),
                    b.getDataAbertura() 
                };
                tabelaBugs.addRow(obj);
            }
        }
}
    

