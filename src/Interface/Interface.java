private String getModuloSelecionado() {
if (buttonGroup2 != null && buttonGroup2.getSelection() != null) {
            String actionCmd = buttonGroup2.getSelection().getActionCommand();
            if (actionCmd != null && !actionCmd.trim().isEmpty()) {
                return actionCmd.trim();
            }
        }

        if (rdoFrontend != null && rdoFrontend.isSelected()) return rdoFrontend.getText().trim();
        if (rdoBackend != null && rdoBackend.isSelected()) return rdoBackend.getText().trim();
        if (rdoBanco != null && rdoBanco.isSelected()) return rdoBanco.getText().trim();
        if (rdoInfra != null && rdoInfra.isSelected()) return rdoInfra.getText().trim();

        return "Geral";
    }
       
    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed

        String nomeBug = txfNome.getText().trim();

        if (nomeBug.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Digite o nome do bug antes de salvar.");
            return;
        }

        beans.Bug bug = new beans.Bug();
        bug.setNome(txfNome.getText().trim());
        bug.setDescricao(txtDescricao.getText().trim());
        bug.setStatus(cmbStatus.getSelectedItem().toString());
        bug.setModulo(getModuloSelecionado());
        bug.setPrioridade(cmbPrioridade.getSelectedItem().toString());
        bug.setDataAbertura(java.time.LocalDate.now());

        Object projSelecionado = cmbProjeto.getSelectedItem();
        if (projSelecionado instanceof beans.Projeto) {
            bug.setIdProjeto(((beans.Projeto) projSelecionado).getId());
        } else {
            bug.setIdProjeto(null);
        }

        new DAO.BugDAO().inserir(bug);
        javax.swing.JOptionPane.showMessageDialog(this, "Bug salvo com sucesso!");

        txfNome.setText("");
        txtDescricao.setText("");
        if (buttonGroup2 != null) {
            buttonGroup2.clearSelection();
        }
        cmbProjeto.setSelectedIndex(0);
    }//GEN-LAST:event_btnSalvarActionPerformed

