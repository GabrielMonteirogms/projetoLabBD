    private void carregarTabela() {
        
      if (tblVisaoGeral == null) {
            System.out.println("Erro: tblVisaoGeral não foi inicializada.");
            return;
        }

        DefaultTableModel model = new DefaultTableModel(
            new Object[][]{},
            new String[]{"ID Bug", "Bug", "Status", "Prioridade", "Projeto", "Equipe", "Funcionários da Equipe"}
        ) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };

        BugDAO dao = new BugDAO();
        List<BugResumo> dados = dao.getVisaoCompleta();

        for (BugResumo item : dados) {
            model.addRow(new Object[]{
                item.getIdBug(),
                item.getNomeBug(),
                item.getStatus(),
                item.getPrioridade(),
                item.getNomeProjeto(),
                item.getNomeEquipe(),
                item.getFuncionariosEquipe()
            });
        }

        tblVisaoGeral.setModel(model);
    }
