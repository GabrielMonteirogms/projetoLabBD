    private void atualizarDashboard() {
BugDAO dao = new BugDAO();
        
        String mod = cmbFiltroModulo.getSelectedItem().toString().trim();
        String prio = cmbFiltroPrioridade.getSelectedItem().toString().trim();
        
        if (mod.isEmpty()) mod = "Todos";
        if (prio.isEmpty()) prio = "Todas";
        
     
        System.out.println("DEBUG -> Aplicando Filtros | Módulo: [" + mod + "] | Prioridade: [" + prio + "]");
        
        List<Bug> filtrados = dao.getBugsFiltrados(mod, prio);
        
 
        if (filtrados != null) {
            System.out.println("DEBUG -> Quantidade de bugs encontrados: " + filtrados.size());
        } else {
            System.out.println("DEBUG -> A lista de bugs voltou NULA do DAO!");
        }
        
        preencherTabela(filtrados);
    }
    
 
    private void preencherTabela(List<Bug> listaBugs) {
        DefaultTableModel modelo = (DefaultTableModel) tblBugs.getModel();
        modelo.setNumRows(0);
        
        if (listaBugs != null) {
            for(Bug b : listaBugs){
                
                Object[] linha = new Object[] {
                    b.getNome(),
                    b.getModulo(),
                    b.getPrioridade(),
                    b.getStatus(),
                    b.getDescricao(),
                    b.getDataAbertura()
                };
                modelo.addRow(linha);
            }
        }
    }
    
    private void exportarRelatorioCSV() {
        
        javax.swing.JFileChooser fileChooser = new javax.swing.JFileChooser();
        fileChooser.setDialogTitle("Salvar Relatório de Bugs");
        
        int userSelection = fileChooser.showSaveDialog(this);

        if (userSelection == javax.swing.JFileChooser.APPROVE_OPTION) {
            java.io.File fileToSave = fileChooser.getSelectedFile();
            
           
            String caminhoArquivo = fileToSave.getAbsolutePath();
            if (!caminhoArquivo.toLowerCase().endsWith(".csv")) {
                caminhoArquivo += ".csv";
            }
            
            try (java.io.FileWriter fw = new java.io.FileWriter(caminhoArquivo)) {
                
             
                fw.write("NOME;MODULO;PRIORIDADE;STATUS;DESCRICAO;DATA_ABERTURA\n");
                
               
                javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tblBugs.getModel();
                
               
                for (int i = 0; i < model.getRowCount(); i++) {
                    String linha = model.getValueAt(i, 0) + ";" +
                                   model.getValueAt(i, 1) + ";" +
                                   model.getValueAt(i, 2) + ";" +
                                   model.getValueAt(i, 3) + ";" +
                                   model.getValueAt(i, 4) + ";" +
                                   model.getValueAt(i, 5) + "\n";
                    fw.write(linha);
                }
                
                javax.swing.JOptionPane.showMessageDialog(this, "Relatório exportado com sucesso para CSV!", "Sucesso", javax.swing.JOptionPane.INFORMATION_MESSAGE);
                
            } catch (Exception e) {
                javax.swing.JOptionPane.showMessageDialog(this, "Erro ao exportar arquivo: " + e.getMessage(), "Erro", javax.swing.JOptionPane.ERROR_MESSAGE);
            }
        }
    }
