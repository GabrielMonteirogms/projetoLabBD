    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
       if (txtNomeEquipe.getText().trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                this,
                "Informe o nome da equipe antes de salvar!",
                "Atenção",
                javax.swing.JOptionPane.WARNING_MESSAGE
            );
            return;
        }

        beans.Equipe e = new beans.Equipe();
        e.setNomeEquipe(txtNomeEquipe.getText().trim());
        e.setLider(txtLider.getText().trim());
        e.setDescricao(txtDescricao.getText().trim());

        DAO.EquipeDAO dao = new DAO.EquipeDAO();
        dao.inserir(e);

        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Equipe cadastrada com sucesso!",
            "Sucesso",
            javax.swing.JOptionPane.INFORMATION_MESSAGE
        );

        txtNomeEquipe.setText("");
        txtLider.setText("");
        txtDescricao.setText("");
    }//GEN-LAST:event_btnSalvarActionPerformed

