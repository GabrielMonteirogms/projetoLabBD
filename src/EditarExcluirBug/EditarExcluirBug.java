    private void btnConsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarActionPerformed
try {
            if (txfId.getText().trim().isEmpty()) {
                JOptionPane.showMessageDialog(this, "Digite um ID para consultar!");
                return;
            }
            
            int idBug = Integer.parseInt(txfId.getText());
            BugDAO bDAO = new BugDAO();
            Bug b = bDAO.getBug(idBug); 
            
            if (b == null) {
                limparFormulario();
                JOptionPane.showMessageDialog(this, "Bug não encontrado na base de dados!");
            } else {
                txfId.setText(String.valueOf(b.getId()));
                txtId_disable.setText(String.valueOf(b.getId()));
                
                
                txfNome1.setText(b.getNome()); 
                txfDescricao.setText(b.getDescricao()); 

                String modulo = b.getModulo();
                if (modulo != null) {
                    switch (modulo) {
                        case "Front-end": rdo_frontend.setSelected(true); break;
                        case "Back-end": rdo_backend.setSelected(true); break;
                        case "Banco de Dados": rdo_BD.setSelected(true); break;
                        case "Infraestrutura": rdo_infra.setSelected(true); break;
                    }
                }
                
                cmb_Prioridade.setSelectedItem(b.getPrioridade());
                cmb_Status.setSelectedItem(b.getStatus());
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Erro: Por favor, insira um ID numérico válido.");
        }
    }//GEN-LAST:event_btnConsultarActionPerformed

