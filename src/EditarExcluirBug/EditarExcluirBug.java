    private void btnAtualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtualizarActionPerformed
if (txtId_disable.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Consulte um Bug primeiro antes de atualizar!");
            return;
        }

      
        String modulo = "";
        if (rdo_frontend.isSelected()) modulo = "Front-end";
        else if (rdo_backend.isSelected()) modulo = "Back-end";
        else if (rdo_BD.isSelected()) modulo = "Banco de Dados";
        else if (rdo_infra.isSelected()) modulo = "Infraestrutura";

        Bug b = new Bug();
        b.setId(Integer.parseInt(txtId_disable.getText()));
        
        // CORRIGIDO: Puxando dos JTextFields corretos!
        b.setNome(txfNome1.getText()); 
        b.setDescricao(txfDescricao.getText());
        
        b.setStatus(cmb_Status.getSelectedItem().toString());
        b.setModulo(modulo);
        b.setPrioridade(cmb_Prioridade.getSelectedItem().toString());

        BugDAO bDAO = new BugDAO();
        bDAO.editar(b); 
        
        JOptionPane.showMessageDialog(this, "Registo atualizado com sucesso!");
        limparFormulario();
    
    }//GEN-LAST:event_btnAtualizarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
 if (txtId_disable.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Consulte um Bug primeiro antes de excluir!");
            return;
        }

        int resposta = JOptionPane.showConfirmDialog(this, "Deseja realmente excluir este registo?",
                "Confirmação", JOptionPane.YES_NO_OPTION);
                
        if (resposta == JOptionPane.YES_OPTION) {
            BugDAO bDAO = new BugDAO();
            bDAO.excluir(Integer.parseInt(txtId_disable.getText())); 
            
            JOptionPane.showMessageDialog(this, "Bug excluído com sucesso!");
            limparFormulario();
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

